-- =============================================================
-- V12__create_business_settings.sql
-- WAC D.S. Appointments
--
-- Configuración operativa de reservas por negocio.
--
-- Relación:
--
-- businesses 1 ---- 1 business_settings
--
-- Esta tabla NO almacena:
--
-- - datos de perfil del negocio
-- - branding
-- - timezone
-- - currency
-- - public_booking_enabled
-- - duración de servicios
--
-- Todo ello permanece en sus entidades correspondientes.
-- =============================================================


-- =============================================================
-- 1. CREATE TABLE
-- =============================================================

CREATE TABLE business_settings (

    -- ---------------------------------------------------------
    -- ID
    -- ---------------------------------------------------------

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    -- ---------------------------------------------------------
    -- BUSINESS
    -- ---------------------------------------------------------

    business_id BIGINT NOT NULL,


    -- ---------------------------------------------------------
    -- BOOKING WINDOW
    -- ---------------------------------------------------------

    minimum_booking_notice_minutes INTEGER NOT NULL DEFAULT 120,

    booking_horizon_days INTEGER NOT NULL DEFAULT 60,


    -- ---------------------------------------------------------
    -- SLOT GENERATION
    -- ---------------------------------------------------------

    slot_interval_minutes INTEGER NOT NULL DEFAULT 15,


    -- ---------------------------------------------------------
    -- DEFAULT BUFFERS
    -- ---------------------------------------------------------

    default_buffer_before_minutes INTEGER NOT NULL DEFAULT 0,

    default_buffer_after_minutes INTEGER NOT NULL DEFAULT 0,


    -- ---------------------------------------------------------
    -- APPOINTMENT CONFIRMATION
    -- ---------------------------------------------------------

    auto_confirm_appointments BOOLEAN NOT NULL DEFAULT TRUE,


    -- ---------------------------------------------------------
    -- ONLINE CANCELLATION
    -- ---------------------------------------------------------

    online_cancellation_enabled BOOLEAN NOT NULL DEFAULT TRUE,

    minimum_cancellation_notice_minutes INTEGER NOT NULL DEFAULT 1440,


    -- ---------------------------------------------------------
    -- ONLINE RESCHEDULING
    -- ---------------------------------------------------------

    online_rescheduling_enabled BOOLEAN NOT NULL DEFAULT TRUE,

    minimum_reschedule_notice_minutes INTEGER NOT NULL DEFAULT 1440,


    -- ---------------------------------------------------------
    -- REMINDERS
    -- ---------------------------------------------------------

    reminders_enabled BOOLEAN NOT NULL DEFAULT TRUE,

    first_reminder_minutes_before INTEGER NOT NULL DEFAULT 1440,

    second_reminder_enabled BOOLEAN NOT NULL DEFAULT FALSE,

    second_reminder_minutes_before INTEGER NOT NULL DEFAULT 120,


    -- ---------------------------------------------------------
    -- OPTIMISTIC LOCKING
    -- ---------------------------------------------------------

    version BIGINT NOT NULL DEFAULT 0,


    -- ---------------------------------------------------------
    -- AUDIT
    -- ---------------------------------------------------------

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,


    -- =========================================================
    -- RELATIONAL CONSTRAINTS
    -- =========================================================

    CONSTRAINT fk_business_settings_business
        FOREIGN KEY (business_id)
        REFERENCES businesses (id)
        ON DELETE CASCADE,

    CONSTRAINT uq_business_settings_business
        UNIQUE (business_id),


    -- =========================================================
    -- BOOKING WINDOW CONSTRAINTS
    -- =========================================================

    CONSTRAINT chk_business_settings_minimum_booking_notice
        CHECK (
            minimum_booking_notice_minutes >= 0
            AND minimum_booking_notice_minutes <= 525600
        ),

    CONSTRAINT chk_business_settings_booking_horizon
        CHECK (
            booking_horizon_days >= 1
            AND booking_horizon_days <= 730
        ),


    -- =========================================================
    -- SLOT CONSTRAINTS
    -- =========================================================

    CONSTRAINT chk_business_settings_slot_interval
        CHECK (
            slot_interval_minutes >= 5
            AND slot_interval_minutes <= 240
        ),


    -- =========================================================
    -- BUFFER CONSTRAINTS
    -- =========================================================

    CONSTRAINT chk_business_settings_buffer_before
        CHECK (
            default_buffer_before_minutes >= 0
            AND default_buffer_before_minutes <= 240
        ),

    CONSTRAINT chk_business_settings_buffer_after
        CHECK (
            default_buffer_after_minutes >= 0
            AND default_buffer_after_minutes <= 240
        ),


    -- =========================================================
    -- CANCELLATION CONSTRAINTS
    -- =========================================================

    CONSTRAINT chk_business_settings_cancellation_notice
        CHECK (
            minimum_cancellation_notice_minutes >= 0
            AND minimum_cancellation_notice_minutes <= 525600
        ),


    -- =========================================================
    -- RESCHEDULING CONSTRAINTS
    -- =========================================================

    CONSTRAINT chk_business_settings_reschedule_notice
        CHECK (
            minimum_reschedule_notice_minutes >= 0
            AND minimum_reschedule_notice_minutes <= 525600
        ),


    -- =========================================================
    -- REMINDER CONSTRAINTS
    -- =========================================================

    CONSTRAINT chk_business_settings_first_reminder
        CHECK (
            first_reminder_minutes_before >= 1
            AND first_reminder_minutes_before <= 525600
        ),

    CONSTRAINT chk_business_settings_second_reminder
        CHECK (
            second_reminder_minutes_before >= 1
            AND second_reminder_minutes_before <= 525600
        ),

    /*
     * No permitimos un segundo recordatorio activo si el
     * sistema general de recordatorios está deshabilitado.
     */
    CONSTRAINT chk_business_settings_second_requires_reminders
        CHECK (
            second_reminder_enabled = FALSE
            OR reminders_enabled = TRUE
        ),

    /*
     * Si existe segundo recordatorio debe ejecutarse
     * más cerca de la cita que el primero.
     *
     * Ejemplo válido:
     *
     * primer recordatorio  = 1440 min
     * segundo recordatorio = 120 min
     */
    CONSTRAINT chk_business_settings_second_reminder_order
        CHECK (
            second_reminder_enabled = FALSE
            OR second_reminder_minutes_before
                < first_reminder_minutes_before
        ),


    -- =========================================================
    -- OPTIMISTIC LOCKING CONSTRAINT
    -- =========================================================

    CONSTRAINT chk_business_settings_version
        CHECK (
            version >= 0
        )
);


-- =============================================================
-- 2. INDEX
-- =============================================================
--
-- PostgreSQL ya crea internamente un índice UNIQUE debido a:
--
-- UNIQUE (business_id)
--
-- Aun así creamos el índice explícito con el nombre utilizado
-- por la entidad JPA.
--
-- Al ser UNIQUE reforzamos también la relación 1:1.
-- =============================================================

CREATE UNIQUE INDEX IF NOT EXISTS idx_business_settings_business_id
    ON business_settings (business_id);


-- =============================================================
-- 3. INITIAL SETTINGS
-- =============================================================
--
-- Creamos automáticamente una configuración predeterminada
-- para todos los businesses existentes.
--
-- Esto incluye actualmente Aura Studio, pero hace la migración
-- segura también si existen más tenants antes de ejecutar V12.
-- =============================================================

INSERT INTO business_settings (

    business_id,

    minimum_booking_notice_minutes,

    booking_horizon_days,

    slot_interval_minutes,

    default_buffer_before_minutes,

    default_buffer_after_minutes,

    auto_confirm_appointments,

    online_cancellation_enabled,

    minimum_cancellation_notice_minutes,

    online_rescheduling_enabled,

    minimum_reschedule_notice_minutes,

    reminders_enabled,

    first_reminder_minutes_before,

    second_reminder_enabled,

    second_reminder_minutes_before,

    version,

    created_at,

    updated_at

)
SELECT

    b.id,

    120,

    60,

    15,

    0,

    0,

    TRUE,

    TRUE,

    1440,

    TRUE,

    1440,

    TRUE,

    1440,

    FALSE,

    120,

    0,

    CURRENT_TIMESTAMP,

    CURRENT_TIMESTAMP

FROM businesses b

WHERE NOT EXISTS (

    SELECT 1

    FROM business_settings bs

    WHERE bs.business_id = b.id

);


